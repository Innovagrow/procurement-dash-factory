"""Ελληνική ταξινομία: περιφέρειες, δικαιούχοι, κλάδοι, κατηγορίες δαπανών."""
from __future__ import annotations

from .textutils import normalize

import re as _re

_WORD_START = r"(?<![0-9a-zα-ω])"
_WORD_END = r"(?![0-9a-zα-ω])"


def _compile_hints(hints: list[str]) -> list[_re.Pattern]:
    """Ταίριασμα σε αρχή λέξης· οι κοντές ενδείξεις μόνο ως ολόκληρη λέξη.

    Έτσι το «Κρήτη» πιάνει και το «Κρήτης» (κλίση), ενώ το «κω» δεν πιάνει
    το «Ενωσιακών».
    """
    patterns = []
    for hint in hints:
        hint = normalize(hint)
        if not hint:
            continue
        suffix = "" if len(hint.strip()) >= 5 else _WORD_END
        patterns.append(_re.compile(_WORD_START + _re.escape(hint.strip()) + suffix))
    return patterns


def _matches(patterns: list[_re.Pattern], haystack: str) -> bool:
    return any(p.search(haystack) for p in patterns)


