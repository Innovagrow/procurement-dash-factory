# --- Κατάσταση πρόσκλησης ----------------------------------------------------

STATUS_OPEN = "OPEN"
STATUS_UPCOMING = "UPCOMING"
STATUS_CLOSED = "CLOSED"
STATUS_UNKNOWN = "UNKNOWN"

_CLOSED_HINTS = ["εληξε", "ολοκληρωθηκε", "κλειστ", "μη ενεργ", "ανενεργ", "ληξη υποβολησ", "εχει λη"]
_UPCOMING_HINTS = ["προδημοσιευση", "αναμενεται", "προσεχω", "θα ενεργοποιηθει", "upcoming"]
_OPEN_HINTS = ["ανοιχτ", "ενεργ", "σε ισχυ", "υποβολη αιτησεων", "ανοιχτη προσκληση", "δεχεται αιτησεισ"]


def detect_status(text: str | None, deadline=None) -> str:
    """Κατάσταση από κείμενο· η προθεσμία υπερισχύει αν έχει παρέλθει."""
    from .textutils import days_until

    if deadline is not None:
        remaining = days_until(deadline)
        if remaining is not None and remaining < 0:
            return STATUS_CLOSED

    haystack = normalize(text)
    if any(h in haystack for h in _UPCOMING_HINTS):
        return STATUS_UPCOMING
    if any(h in haystack for h in _CLOSED_HINTS):
        return STATUS_CLOSED
    if any(h in haystack for h in _OPEN_HINTS):
        return STATUS_OPEN
    if deadline is not None:
        return STATUS_OPEN
    return STATUS_UNKNOWN


