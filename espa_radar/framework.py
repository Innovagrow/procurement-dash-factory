"""Σε ποιο ταμείο ή θεσμικό πλαίσιο ανήκει ένα πρόγραμμα.

Η πηγή από την οποία βρέθηκε κάτι δεν λέει από πού χρηματοδοτείται: η Διαύγεια
δημοσιεύει και ΕΣΠΑ και Αναπτυξιακό Νόμο και ΚΑΠ. Ο χρήστης όμως σκέφτεται σε
ταμεία — «θέλω τα ΕΣΠΑ» — οπότε αυτό είναι ο σωστός άξονας φιλτραρίσματος.
"""
