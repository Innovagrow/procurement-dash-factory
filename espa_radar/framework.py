        r"ΕΛ\.?ΙΔ\.?Ε\.?Κ|ΕΛΙΔΕΚ|Horizon|Ορ[ίι]ζοντα[ςσ]\s+Ευρ[ώω]πη|ΓΓΕΚ|"
